export const translations: Record<Locale, Record<MessageKey, string>> = {
  uz,
  ru,
  en,
};

export function readStoredLocale(): Locale {
  try {
    const value = localStorage.getItem(LANG_STORAGE_KEY);
    if (value === "uz" || value === "ru" || value === "en") return value;
  } catch {
    /* ignore */
  }
  return "uz";
}

export function formatMessage(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>
) {
  let text = translations[locale][key] || translations.uz[key] || key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export function localeTag(locale: Locale) {
  return locale === "ru" ? "ru-RU" : locale === "en" ? "en-US" : "uz-UZ";
}

export function monthLabels(locale: Locale) {
  const tag = localeTag(locale);
  return Array.from({ length: 12 }, (_, month) =>
    new Date(2020, month, 1).toLocaleString(tag, { month: "short" })
  );
}

export function countryLabel(
  locale: Locale,
  code?: string | null,
  fallback?: string | null
) {
  if (!code || code === "XX" || code === "LOCAL") {
    return formatMessage(locale, "common.unknown");
  }
  const key = `country.${code}` as MessageKey;
  if (Object.prototype.hasOwnProperty.call(uz, key)) {
    return formatMessage(locale, key);
  }
  return fallback || code;
}
